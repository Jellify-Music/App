import { useMutation } from '@tanstack/react-query'
import { useNavigation } from '@react-navigation/native'
import { NativeStackNavigationProp } from '@react-navigation/native-stack'
import Toast from 'react-native-toast-message'
import LibraryStackParamList from '@/src/screens/Library/types'
import { generatePlaylistWithAudioMuseAI, saveAudioMuseAIPlaylist } from './utils'
import { refreshUserPlaylists } from '../../queries/playlist/cache'
import { refreshAndroidAutoLibrary } from '../../../services/auto/android-auto'
import { refreshCarPlayLibrary } from '../../../services/auto/carplay'
import { applyHapticFeedback } from '../../../utils/haptics'
import { handleError } from '../../../utils/errors'
import { LoggingContext } from '../../../utils/logging'

/**
 * Hook to have AudioMuse AI pick tracks for a playlist from a natural-language request
 *
 * @returns A mutation object for generating the playlist
 */
export const useGeneratePlaylistWithAudioMuseAI = () =>
	useMutation({
		mutationFn: generatePlaylistWithAudioMuseAI,
		onSuccess: () => applyHapticFeedback('success'),
		onError: (error) => {
			handleError(error, LoggingContext.Playlist, 'Failed to generate playlist')
		},
	})

/**
 * Hook to save tracks generated by AudioMuse AI as a playlist
 *
 * @returns A mutation object for saving the playlist
 */
export const useSaveAudioMuseAIPlaylist = () => {
	const libraryStackNavigation = useNavigation<NativeStackNavigationProp<LibraryStackParamList>>()

	return useMutation({
		mutationFn: ({ name, itemIds }: { name: string; itemIds: string[] }) =>
			saveAudioMuseAIPlaylist(name, itemIds),
		onSuccess: async (_data, { name }) => {
			// The response only carries the new id inside a message, so refetch instead
			await refreshUserPlaylists()

			refreshAndroidAutoLibrary()
			refreshCarPlayLibrary('playlists')
			applyHapticFeedback('success')

			Toast.show({
				text1: 'Playlist created',
				text2: `Created playlist ${name}`,
				type: 'success',
			})

			libraryStackNavigation.goBack()
		},
		onError: (error) => {
			handleError(error, LoggingContext.Playlist, 'Failed to save generated playlist')
		},
	})
}
