import { ApiNotAvailableError } from '../../../../types/errors'
import { getApi } from '../../../../stores/auth/utils'
import { getAudioMuseApi } from '@jellify-music/audiomuse-ai-jellyfin-sdk'

/**
 * Generates a playlist using the AudioMuse AI API based on the user's input.
 *
 * This only picks the tracks - use {@link saveAudioMuseAIPlaylist} to save them
 *
 * @param userInput The input provided by the user to generate the playlist
 *
 * @throws {ApiNotAvailableError} If the API is not available
 *
 * @returns The generated playlist data from the AudioMuse AI API
 */
export async function generatePlaylistWithAudioMuseAI(userInput: string) {
	const api = getApi()

	if (!api) throw new ApiNotAvailableError()

	const { data } = await getAudioMuseApi(api).chatPlaylist({
		userInput,
	})

	return data
}

/**
 * Saves tracks generated by {@link generatePlaylistWithAudioMuseAI} as a Jellyfin playlist
 *
 * @param name The name of the new playlist
 * @param itemIds The Jellyfin item ids of the tracks to add, in order
 *
 * @throws {ApiNotAvailableError} If the API is not available
 *
 * @returns The response message from the AudioMuse AI API
 */
export async function saveAudioMuseAIPlaylist(name: string, itemIds: string[]) {
	const api = getApi()

	if (!api) throw new ApiNotAvailableError()

	const { data } = await getAudioMuseApi(api).createChatPlaylist({
		playlist_name: name,
		item_ids: itemIds,
	})

	return data
}
